"""Build the headless patcher for the authoritative Rhino jewelry core.

The patcher itself runs inside Rhino.Compute.  It loads the SHA-pinned source
core, replaces the smoke-test constants in the existing core geometry nodes,
adds a stable JSON input hook to each geometry cluster, connects the root
``RH_IN:json_string``/``RH_IN:job_id`` contract, and saves a derivative outside
the repository.  The source ``.gh`` is never modified.
"""

