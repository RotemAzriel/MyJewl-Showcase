"""Internal catalog retrieval index for Lane B (Goal 0005, Stage 2).

"Catalog" here always means **MyJewl's internal validated catalog** — configs
generated by ``scripts/generate_tier1_configs.py`` (the planned internal catalog
generator), gated by the live schema + constraint engine, and rendered from
receipt-backed Rhino geometry. It is never a retailer's catalog, and no
retailer-specific style label enters it unless the canonical schema already
represents that axis. ``fast_mvp/catalog/manifest.json`` is a **development
fixture only** and is not this index.

Holds the embedded catalog renders and answers **shape-filtered** nearest
neighbour queries. The typed stone shape is a hard filter, not a feature: the
ratified R-1 metric is Recall@K *within the typed shape*, and the customer has
already told us the shape, so candidates of another shape are never considered.

**Metal is not a matching axis.** It is a typed input and a cost/appearance
overlay (settled decision 6), randomised per render shard precisely so it carries
no signal. It is therefore never a filter, never a scored attribute, and never
part of the reported mounting — it survives only as render provenance.

Backed by ``hnswlib`` when it is installed and by exact cosine search otherwise.
At pilot scale (~3.6k vectors) the exact path is fast and gives identical
results, so the two are interchangeable; the index records which one built it.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

EMBEDDINGS_FILENAME = "embeddings.npy"
METADATA_FILENAME = "index_metadata.json"

# The mounting axes the image lane may infer — the whole of its output contract.
# Anything absolute (stone geometry, ring size) is a typed input, and so is metal;
# all are deliberately absent.
ATTRIBUTE_FIELDS = (
    "center_setting",
    "prong_count",
    "band_width_ratio",
    "band_thickness_ratio",
)

# Render-appearance provenance: what the catalog shard happened to be rendered in.
# Reported for traceability, never scored, never matched on.
RENDER_PROVENANCE_FIELDS = ("metal_alloy", "metal_color_family")


@dataclass(frozen=True)
class Neighbor:
    row: int
    similarity: float
    record: dict[str, Any]

    def to_json(self) -> dict[str, Any]:
        return {
            "config_id": self.record.get("config_id"),
            "image_path": self.record.get("image_path"),
            "similarity": round(float(self.similarity), 5),
            "mounting": {
                field: self.record.get(field)
                for field in ATTRIBUTE_FIELDS
                if self.record.get(field) is not None
            },
            # Kept out of "mounting" on purpose: the render's metal is a nuisance
            # variable, not part of the match.
            "render_provenance": {
                field: self.record.get(field)
                for field in RENDER_PROVENANCE_FIELDS
                if self.record.get(field) is not None
            },
        }


class CatalogIndex:
    """Embedded catalog renders plus their mounting metadata."""

    def __init__(
        self,
        embeddings: np.ndarray,
        records: list[dict[str, Any]],
        metadata: dict[str, Any],
    ) -> None:
        if embeddings.ndim != 2:
            raise ValueError("embeddings must be a 2-D matrix")
        if len(records) != embeddings.shape[0]:
            raise ValueError(
                f"metadata/embedding mismatch: {len(records)} records vs "
                f"{embeddings.shape[0]} rows"
            )
        self.embeddings = embeddings.astype(np.float32)
        self.records = records
        self.metadata = metadata
        self._rows_by_shape: dict[str, list[int]] = {}
        for row, record in enumerate(records):
            shape = str(record.get("stone_shape", "")).strip().lower()
            self._rows_by_shape.setdefault(shape, []).append(row)

    # -- persistence -------------------------------------------------------

    @classmethod
    def load(cls, index_dir: str | Path) -> "CatalogIndex":
        index_dir = Path(index_dir)
        embeddings = np.load(index_dir / EMBEDDINGS_FILENAME)
        payload = json.loads((index_dir / METADATA_FILENAME).read_text(encoding="utf-8"))
        return cls(embeddings, payload["records"], payload.get("index", {}))

    def save(self, index_dir: str | Path) -> dict[str, Any]:
        index_dir = Path(index_dir)
        index_dir.mkdir(parents=True, exist_ok=True)
        np.save(index_dir / EMBEDDINGS_FILENAME, self.embeddings)
        payload = {"index": self.metadata, "records": self.records}
        (index_dir / METADATA_FILENAME).write_text(
            json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        return {
            "index_dir": str(index_dir),
            "vectors": int(self.embeddings.shape[0]),
            "dimension": int(self.embeddings.shape[1]),
        }

    # -- query -------------------------------------------------------------

    @property
    def shapes(self) -> tuple[str, ...]:
        return tuple(sorted(self._rows_by_shape))

    def rows_for_shape(self, stone_shape: str) -> list[int]:
        return list(self._rows_by_shape.get(str(stone_shape).strip().lower(), []))

    def query(
        self,
        vector: np.ndarray,
        *,
        stone_shape: str,
        top_k: int = 5,
        exclude_config_ids: frozenset[str] | None = None,
    ) -> list[Neighbor]:
        """Return the top-K catalog neighbours **within the typed shape**.

        The typed stone shape is the only filter. There is deliberately no metal
        filter or metal re-rank: metal must not affect geometry matching.
        """
        rows = self.rows_for_shape(stone_shape)
        if exclude_config_ids:
            rows = [
                row
                for row in rows
                if str(self.records[row].get("config_id")) not in exclude_config_ids
            ]
        if not rows:
            return []
        query_vector = vector.astype(np.float32)
        norm = float(np.linalg.norm(query_vector))
        if norm > 1e-12:
            query_vector = query_vector / norm
        similarities = self.embeddings[rows] @ query_vector
        order = np.argsort(-similarities)[: max(1, int(top_k))]
        return [
            Neighbor(
                row=rows[int(position)],
                similarity=float(similarities[int(position)]),
                record=self.records[rows[int(position)]],
            )
            for position in order
        ]


def try_build_hnsw(embeddings: np.ndarray) -> dict[str, Any]:
    """Build an HNSW graph when hnswlib is available; report which path ran.

    The exact path returns identical neighbours at pilot scale, so this is
    recorded as provenance rather than gated on.
    """
    try:
        import hnswlib
    except ImportError:
        return {"structure": "exact_cosine", "hnswlib": None}
    index = hnswlib.Index(space="cosine", dim=int(embeddings.shape[1]))
    index.init_index(max_elements=int(embeddings.shape[0]), ef_construction=200, M=16)
    index.add_items(embeddings, np.arange(embeddings.shape[0]))
    index.set_ef(64)
    return {
        "structure": "hnsw",
        "hnswlib": getattr(hnswlib, "__version__", "unknown"),
        "ef_construction": 200,
        "M": 16,
    }
